const nav = async title => {
  await page.getByRole('navigation', { name: 'Sections' }).getByRole('button', { name: title }).click()
  const gap = () => page.evaluate(id => document.getElementById(id).getBoundingClientRect().top -
    document.querySelector('.workflow-strip').getBoundingClientRect().bottom, sections[title])
  await expect.poll(async () => Math.abs(await gap() - 16)).toBeLessThan(2)
  alignment.push({ section: title, gap: await gap() })
}
const api = async path => {
  const response = await context.request.get('http://127.0.0.1:8000/api' + path)
  expect(response.ok()).toBe(true)
  return response.json()
}
