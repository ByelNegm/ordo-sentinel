import { chromium, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'

const output = process.env.UI_EVIDENCE_DIR || '/home/ubuntu/blackbox-evidence/ui'
await mkdir(output, { recursive: true })
const browser = await chromium.connectOverCDP(process.env.CDP_URL || 'http://localhost:29229')
const context = await browser.newContext({ viewport: { width: 1440, height: 1200 }, reducedMotion: 'reduce' })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const nav = title => page.getByRole('navigation', { name: 'Sections' }).getByRole('button', { name: title }).click()
const api = async path => {
  const response = await context.request.get('http://127.0.0.1:8000/api' + path)
  expect(response.ok()).toBe(true)
  return response.json()
}
const shot = name => page.screenshot({ path: output + '/premium_' + name + '.png', animations: 'disabled' })
const noOverflow = async () => expect(await page.evaluate(() =>
  document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)

try {
  await page.goto(process.env.UI_URL || 'http://localhost:5173')
  await expect(page.getByTestId('checks-passed')).toHaveText('7/7 checks')
  await page.evaluate(() => document.fonts.ready)
  await nav('Attack Simulator')
  await page.getByRole('button', { name: 'Reset baseline', exact: true }).click()
  await expect.poll(async () => (await api('/overview')).volume.instructions).toBe(100)
  await nav('Bank Operations')
  await expect(page.locator('h1')).toHaveText('Trust, independently verified.')
  await noOverflow()
  expect(await page.locator('body').evaluate(() => getComputedStyle(document.documentElement).fontFamily)).toContain('Geist')
  expect(await page.locator('.money').first().evaluate(node => getComputedStyle(node).fontFamily)).toContain('Geist Mono')
  await expect(page.locator('.workflow-steps li')).toHaveCount(6)
  await expect(page.locator('.brand-mark svg')).toBeVisible()
  await shot('healthy')
  await nav('Attack Simulator')
  await page.getByRole('button', { name: 'Start traffic', exact: true }).click()
  await page.getByRole('button', { name: 'Inject Duplicate Settlement', exact: true }).click()
  await expect(page.getByTestId('integrity-status')).toHaveText('VIOLATED', { timeout: 20000 })
  await nav('Incident Investigation')
  await expect(page.getByTestId('incident-summary')).toContainText('settled twice')
  await expect(page.getByTestId('incident-summary')).toBeInViewport({ ratio: 1 })
  await expect(page.locator('.lineage').first()).toBeVisible()
  await nav('Incident Investigation')
  await shot('violated')
  await expect(page.getByTestId('incident-status')).toHaveText('awaiting approval', { timeout: 25000 })
  await nav('Recovery Sandbox')
  await expect(page.getByTestId('sandbox-result')).toHaveText('SANDBOX PASSED')
  await expect(page.getByTestId('sandbox-runner')).toContainText('Daytona sandbox')
  await expect(page.getByTestId('sandbox-runner')).toContainText('remote checks match')
  await expect(page.getByTestId('sandbox-runner')).toBeInViewport({ ratio: 1 })
  await page.getByRole('button', { name: 'Wrong amount (+100 minor)', exact: true }).click()
  await expect(page.getByTestId('challenge-result')).toHaveText('SANDBOX REJECTED')
  await expect(page.getByTestId('challenge-applied')).toHaveText('Blocked before applying to the sandbox copy')
  await expect(page.getByText(/Real ledger unchanged: \d+ entries before = \d+ after/)).toBeVisible()
  await nav('Recovery Sandbox')
  await noOverflow()
  await shot('sandbox')
  const incident = (await api('/incidents'))[0]
  expect(incident.sandbox.runner).toBe('daytona')
  expect(incident.sandbox.remote_match).toBe(true)
  await page.getByRole('combobox', { name: 'Approver' }).selectOption('blackbox-agent')
  await page.getByRole('button', { name: 'Approve recovery', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('HTTP 403')
  await expect(page.getByTestId('incident-status')).toHaveText('awaiting approval')
  await page.getByRole('combobox', { name: 'Approver' }).selectOption('ops.lead@bank')
  await page.getByRole('button', { name: 'Approve recovery', exact: true }).click()
  await expect(page.getByTestId('incident-status')).toHaveText('resolved')
  await expect(page.getByTestId('checks-passed')).toHaveText('7/7 checks')
  await nav('Recovery Verification')
  await expect(page.getByRole('heading', { name: 'INTEGRITY RESTORED', exact: true })).toBeInViewport({ ratio: 1 })
  await noOverflow()
  await shot('resolved')
  await page.getByRole('button', { name: 'Release settlement-svc', exact: true }).click()
  await expect.poll(async () => (await api('/overview')).volume.held).toBe(0)
  await nav('Attack Simulator')
  await page.getByRole('button', { name: 'Reset baseline', exact: true }).click()
  await expect.poll(async () => (await api('/overview')).volume.instructions).toBe(100)
  const final = await api('/overview')
  expect(final.traffic_running).toBe(false)
  expect(final.integrity.status).toBe('healthy')
  expect(final.open_incidents).toBe(0)
  expect(final.services[0].status).toBe('running')
  expect(errors).toEqual([])
  await writeFile(output + '/premium_results.json', JSON.stringify({ errors, sandbox: incident.sandbox, final }, null, 2))
  console.log('PASS premium duplicate: inject -> evidence -> Daytona match -> unsafe challenge rejected -> agent 403 -> ops approval -> 7/7 -> release -> reset')
  console.log('PASS premium presentation: self-hosted fonts, six guide steps, Phosphor mark, no page overflow, no browser errors')
  console.log('PASS screenshots: premium_healthy.png, premium_violated.png, premium_sandbox.png, premium_resolved.png')
} catch (error) {
  console.error('Browser errors:', errors)
  await page.screenshot({ path: output + '/premium_failure.png', animations: 'disabled' })
  throw error
} finally {
  await context.close()
  await browser.close()
}
